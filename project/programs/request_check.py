"""
Задание 3.3. Проверка заявок на передачу данных за границу.
При запуске обрабатывает три заявки и сохраняет отчёт reports/transfer_report.txt.
"""
import sys
import pathlib
import datetime

КОРЕНЬ_ПРОЕКТА = pathlib.Path(__file__).resolve().parent.parent
if str(КОРЕНЬ_ПРОЕКТА) not in sys.path:
    sys.path.insert(0, str(КОРЕНЬ_ПРОЕКТА))

from programs.country_check import проверить_страну
from data.transfer_requests import ЗАЯВКИ_НА_ПЕРЕДАЧУ

ПУТЬ_ОТЧЁТА = КОРЕНЬ_ПРОЕКТА / "reports" / "transfer_report.txt"
РАБОЧИХ_ДНЕЙ_НА_РАССМОТРЕНИЕ = 10


def _в_дату(значение):
    """Строка ГГГГ-ММ-ДД или дата -> datetime.date."""
    if isinstance(значение, datetime.datetime):
        return значение.date()
    if isinstance(значение, datetime.date):
        return значение
    return datetime.datetime.strptime(str(значение), "%Y-%m-%d").date()


def прибавить_рабочие_дни(начало, количество):
    """Дата через N рабочих дней (пн–пт; праздничный календарь не учитывается)."""
    дата = начало
    while количество > 0:
        дата += datetime.timedelta(days=1)
        if дата.weekday() < 5:
            количество -= 1
    return дата


def проверить_заявку(заявка):
    """
    Проверяет страну, уведомление Роскомнадзора (10 рабочих дней) и особые согласия.
    Возвращает словарь с итоговым приговором и списком причин.
    """
    страна = проверить_страну(заявка["страна_получатель"])
    причины, условия = [], []     # причины — что блокирует передачу; условия — что ещё нужно сделать
    блокировка = False
    сегодня = _в_дату(заявка["текущая_дата"])
    начало_разрешено = None

    # 1. Страна
    причины.append(f"Страна: {страна['название']} ({страна['код']}) — {страна['приговор']}.")
    if страна["приговор"] == "запрещено":
        блокировка = True

    # 2. Уведомление Роскомнадзора и 10 рабочих дней
    if not заявка["уведомлён_роскомнадзор"]:
        блокировка = True
        причины.append("Роскомнадзор не уведомлён: передача до направления уведомления запрещена (ч. 3 ст. 12 152-ФЗ).")
    else:
        дата_уведомления = _в_дату(заявка["дата_уведомления"])
        конец_срока = прибавить_рабочие_дни(дата_уведомления, РАБОЧИХ_ДНЕЙ_НА_РАССМОТРЕНИЕ)
        if страна["дней_ожидания"] == 0:
            причины.append(f"Уведомление направлено {дата_уведомления}: для страны с достаточной защитой "
                           "ожидание решения не требуется.")
        elif сегодня > конец_срока:
            причины.append(f"Уведомление направлено {дата_уведомления}: 10 рабочих дней истекли {конец_срока}, "
                           "запрета Роскомнадзора нет (при условии, что решение не поступало).")
        else:
            блокировка = True
            начало_разрешено = конец_срока + datetime.timedelta(days=1)
            причины.append(f"Уведомление направлено {дата_уведомления}: 10 рабочих дней ещё не прошли "
                           f"(истекают {конец_срока}); передача допускается не ранее {начало_разрешено} "
                           "(ч. 12 ст. 12 152-ФЗ).")

    # 3. Особые согласия по видам данных
    виды = заявка["виды_передаваемых_данных"]
    if "биометрические" in виды:
        if заявка["есть_согласие"]:
            причины.append("Биометрия: письменное согласие есть (ч. 1 ст. 11 152-ФЗ).")
        else:
            блокировка = True
            причины.append("Биометрия: нужно письменное согласие (ч. 1 ст. 11 152-ФЗ), его нет.")
    if "специальные" in виды:
        if заявка["есть_согласие"]:
            причины.append("Спецкатегории: письменное согласие есть (п. 1 ч. 2 ст. 10 152-ФЗ).")
        else:
            блокировка = True
            причины.append("Спецкатегории: нужно письменное согласие (п. 1 ч. 2 ст. 10 152-ФЗ), его нет.")
    if "иные" in виды and not заявка["есть_согласие"]:
        условия.append("Для иных данных подтвердить согласие (ч. 1 ст. 9) или другое основание по ч. 1 ст. 6 152-ФЗ.")
    if "общедоступные" in виды:
        причины.append("Общедоступные данные: отдельное согласие на передачу не требуется.")
    if ("биометрические" in виды or "специальные" in виды) and страна["дней_ожидания"] == 10:
        условия.append("Для такого вида данных Роскомнадзор может запросить дополнительные сведения (+10 рабочих дней).")

    # Условия самой страны, которые остаются невыполненными (только если передача не заблокирована)
    if страна["приговор"] == "разрешено при условиях":
        условия.extend(у for у in страна["условия"][1:] if "уведомление" not in у.lower() or "сведения" in у.lower())

    if блокировка:
        приговор = "запрещено"
        условия.insert(0, "Устранить причины, перечисленные выше, и повторить проверку.")
    elif условия:
        приговор = "разрешено при условиях"
    else:
        приговор = "разрешено"

    return {"номер": заявка.get("номер"), "страна": страна, "приговор": приговор,
            "причины": причины, "условия": условия, "дата_начала_передачи": начало_разрешено}


def _текст_результата(заявка, итог):
    строки = [f"Заявка № {заявка['номер']}: {заявка['цель_передачи']}",
              f"  Страна-получатель: {итог['страна']['название']} ({итог['страна']['код']}); "
              f"данные: {', '.join(заявка['виды_передаваемых_данных'])}; людей: {заявка['число_людей']}",
              f"  ИТОГОВЫЙ ПРИГОВОР: {итог['приговор'].upper()}", "  Причины:"]
    строки += [f"    - {п}" for п in итог["причины"]]
    if итог["условия"]:
        строки.append("  Условия:")
        строки += [f"    - {у}" for у in итог["условия"]]
    return "\n".join(строки)


def обработать_все_заявки():
    части = ["ОТЧЁТ ПО ТРАНСГРАНИЧНОЙ ПЕРЕДАЧЕ ДАННЫХ", "=" * 70]
    for заявка in ЗАЯВКИ_НА_ПЕРЕДАЧУ:
        части.append(_текст_результата(заявка, проверить_заявку(заявка)))
        части.append("-" * 70)
    текст = "\n".join(части) + "\n"
    ПУТЬ_ОТЧЁТА.parent.mkdir(exist_ok=True)
    ПУТЬ_ОТЧЁТА.write_text(текст, encoding="utf-8")
    return текст


if __name__ == "__main__":
    print(обработать_все_заявки())
    print(f"Отчёт сохранён: {ПУТЬ_ОТЧЁТА}")
