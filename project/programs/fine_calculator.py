# -*- coding: utf-8 -*-
"""
Задание 4.2. Расчёт штрафа для юридического лица по ст. 13.11 КоАП РФ
(редакция с 30.05.2025, ФЗ от 30.11.2024 № 420-ФЗ).
"""

ПОТОЛОК_ОБОРОТНОГО_ШТРАФА = 500_000_000


def _р(число):
    """Число с пробелами между разрядами."""
    return f"{число:,}".replace(",", " ")


def _оборотный(выручка, нижний_порог, доля_мин=0.01, доля_макс=0.03):
    """От 1 до 3 % выручки, но не менее нижнего порога и не более 500 млн руб."""
    наим = min(ПОТОЛОК_ОБОРОТНОГО_ШТРАФА, max(нижний_порог, round(выручка * доля_мин)))
    наиб = min(ПОТОЛОК_ОБОРОТНОГО_ШТРАФА, max(нижний_порог, round(выручка * доля_макс)))
    return наим, наиб


def рассчитать_штраф(вид_нарушения, число_людей, повторно, годовая_выручка, виды_данных=None):
    """
    вид_нарушения: «утечка малого размера», «утечка среднего размера», «утечка крупного размера»,
                   «отсутствие уведомления», «нарушение по биометрии», «нарушение по согласию».
    Возвращает словарь: наименьший/наибольший штраф, применим ли оборотный штраф, обоснование.
    виды_данных — необязательный список видов данных (нужен для утечек спецкатегорий/биометрии).
    """
    виды_данных = виды_данных or []
    выручка = годовая_выручка
    оборотный = False
    обоснование = []

    if вид_нарушения.startswith("утечка"):
        # Размер утечки определяется по числу людей, а не по названию вида (ч. 12–14 ст. 13.11)
        if число_людей > 100_000:
            уровень, наим, наиб, часть = "крупная", 10_000_000, 15_000_000, "ч. 14"
        elif число_людей > 10_000:
            уровень, наим, наиб, часть = "средняя", 5_000_000, 10_000_000, "ч. 13"
        elif число_людей >= 1_000:
            уровень, наим, наиб, часть = "малая", 3_000_000, 5_000_000, "ч. 12"
        else:
            уровень, наим, наиб, часть = "до 1 000 человек", 150_000, 300_000, "ч. 1"
        обоснование.append(f"Утечка {уровень} ({число_людей} чел.): {часть} ст. 13.11 КоАП РФ.")
        заявленный = {"малого": "малая", "среднего": "средняя", "крупного": "крупная"}.get(
            вид_нарушения.replace("утечка ", "").replace(" размера", ""))
        if заявленный != уровень and not уровень.startswith("до 1"):
            обоснование.append(f"Заявленный вид «{вид_нарушения}» скорректирован по числу людей.")

        if "биометрические" in виды_данных:
            if повторно:
                наим, наиб = _оборотный(выручка, 25_000_000)
                оборотный, часть = True, "ч. 18"
                обоснование.append("Повторная утечка биометрии: ч. 18 ст. 13.11 — 1–3 % выручки, "
                                   "не менее 25 млн и не более 500 млн руб.")
            else:
                наим, наиб = 15_000_000, 20_000_000
                обоснование.append("Утечка биометрических данных: ч. 17 ст. 13.11 — 15–20 млн руб.")
        elif повторно:
            наим, наиб = _оборотный(выручка, 20_000_000)
            оборотный = True
            if "специальные" in виды_данных:
                обоснование.append("Повторная утечка спецкатегорий: отдельного повторного состава нет, "
                                   "применена консервативная оценка по ч. 15 ст. 13.11.")
            обоснование.append("Повторная утечка: ч. 15 ст. 13.11 — оборотный штраф 1–3 % выручки за год, "
                               "не менее 20 млн и не более 500 млн руб.")
        elif "специальные" in виды_данных:
            наим, наиб = 10_000_000, 15_000_000
            обоснование.append("Утечка специальных категорий: ч. 16 ст. 13.11 — 10–15 млн руб.")
        if оборотный:
            обоснование.append("Выручка {} руб. → 1 % = {}, 3 % = {} руб.".format(
                _р(выручка), _р(round(выручка * 0.01)), _р(round(выручка * 0.03))))
        return _итог(наим, наиб, оборотный, обоснование)

    if вид_нарушения == "отсутствие уведомления":
        # ч. 10 (о начале обработки): 100–300 тыс.; ч. 11 (об инциденте): 1–3 млн руб.
        наим, наиб = 100_000, 3_000_000
        обоснование.append("Неуведомление Роскомнадзора: ч. 10 ст. 13.11 (100–300 тыс. руб., уведомление "
                           "о начале обработки) и ч. 11 ст. 13.11 (1–3 млн руб., уведомление об утечке); "
                           "за трансграничное уведомление дополнительно ст. 19.7 КоАП РФ.")
    elif вид_нарушения == "нарушение по биометрии":
        # от ч. 2 (300–700 тыс.) до потолка ч. 17 (20 млн, если нарушение привело к утечке)
        наим, наиб = 300_000, 20_000_000
        обоснование.append("Нарушение порядка обработки биометрии: ч. 2 ст. 13.11 (300–700 тыс. руб.); "
                           "верхняя граница — 20 млн руб. по ч. 17 ст. 13.11, если нарушение приведёт к утечке.")
        if повторно:
            обоснование.append("Повторная утечка биометрии повлекла бы оборотный штраф по ч. 18 ст. 13.11.")
    elif вид_нарушения == "нарушение по согласию":
        наим, наиб = 300_000, 700_000
        обоснование.append("Обработка без надлежащего согласия или с нарушением ст. 9: "
                           "ч. 2 ст. 13.11 — 300–700 тыс. руб.")
    else:
        raise ValueError(f"Неизвестный вид нарушения: {вид_нарушения}")

    if повторно:
        # учебное допущение: повторность — отягчающее обстоятельство (п. 2 ч. 1 ст. 4.3 КоАП РФ),
        # штраф смещается в верхнюю половину санкции
        наим = (наим + наиб) // 2
        обоснование.append("Повторность: п. 2 ч. 1 ст. 4.3 КоАП РФ (отягчающее обстоятельство) — "
                           "штраф смещён в верхнюю половину диапазона.")
    return _итог(наим, наиб, False, обоснование)


def _итог(наим, наиб, оборотный, обоснование):
    return {
        "наименьший_штраф_руб": int(наим),
        "наибольший_штраф_руб": int(наиб),
        "оборотный_штраф_применим": оборотный,
        "правовое_обоснование": " ".join(обоснование),
    }


