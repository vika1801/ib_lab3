def состояние_по_штрафу(штраф):
    if штраф == 0:
        return "в порядке"
    return "грубая ошибка" if штраф >= 500_000 else "замечание"


def проверить_политику(текст):
    """Политика: не менее 1500 слов и обязательные разделы (ч. 3 ст. 13.11 КоАП РФ — до 60 000 руб.)."""
    низ = текст.lower()
    разделы = {"цели": "цели обработки", "виды данных": "виды обрабатываемых данных",
               "правовые основания": "правовые основания", "сроки": "сроки обработки",
               "права человека": "права субъектов", "чьи данные обрабатываются": "категории субъектов",
               "контакт ответственного": "контактные данные ответственного"}
    нет = [к for к, ф in разделы.items() if ф not in низ]
    слов = len(текст.split())
    причины = []
    if слов < 1500:
        причины.append(f"в политике {слов} слов, требуется не менее 1500")
    if нет:
        причины.append("нет разделов: " + ", ".join(нет))
    штраф = 60_000 if причины else 0
    return штраф, ("; ".join(причины) if причины else f"{слов} слов, все 7 обязательных разделов на месте")


def проверить_образец_уведомления(текст):
    """Образец уведомления: должны быть подстановочные поля для ч. 3.1 ст. 21."""
    нужные = ["вид_уведомления", "дата_обнаружения", "число_пострадавших", "виды_данных",
              "причина_утечки", "принятые_меры", "ответственный", "сведения_по_виду"]
    нет = [п for п in нужные if "{" + п + "}" not in текст]
    return 0, ("не хватает полей: " + ", ".join(нет) if нет else "все обязательные поля для подстановки на месте")


def проверить_документы():
    from programs.consent_check import проверить_согласие
    итоги = []
    for файл in sorted(ПАПКА_ДОКУМЕНТОВ.glob("*.txt")):
        текст = файл.read_text(encoding="utf-8")
        if файл.name.endswith("_consent.txt"):
            вид = "работник" if "employee" in файл.name else "клиент"
            р_ = проверить_согласие(текст, вид)
            штраф, причина = р_["размер_штрафа_руб"], р_["пояснение"]
        elif файл.name == "policy.txt":
            штраф, причина = проверить_политику(текст)
        elif файл.name == "leak_notification.txt":
            штраф, причина = проверить_образец_уведомления(текст)
            состояние = "в порядке" if not штраф and "не хватает" not in причина else "замечание"
            итоги.append({"файл": файл.name, "состояние": состояние, "причина": причина, "штраф": штраф})
            continue
        else:
            continue
        итоги.append({"файл": файл.name, "состояние": состояние_по_штрафу(штраф), "причина": причина, "штраф": штраф})
    return итоги


