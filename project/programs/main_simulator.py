ВЕС_НАРУШЕНИЙ = {"нарушение по биометрии": 15, "отсутствие уведомления": 10, "нарушение по согласию": 8}
ВЕС_ДОКУМЕНТОВ = {"грубая ошибка": 10, "замечание": 4, "в порядке": 0}


def оценить(организация, документы, пересчёт, итог_запроса):
    """Оценка 0–100: из 100 вычитаются штрафные баллы; считается общий риск штрафов (мин и макс)."""
    баллы = sum(ВЕС_НАРУШЕНИЙ.get(п["нарушение"]["параметры_расчёта"]["вид"], 8) for п in пересчёт)
    баллы += sum(ВЕС_ДОКУМЕНТОВ[д["состояние"]] for д in документы)
    риск_мин = sum(п["расчёт"]["наименьший_штраф_руб"] for п in пересчёт) + sum(д["штраф"] for д in документы)
    риск_макс = sum(п["расчёт"]["наибольший_штраф_руб"] for п in пересчёт) + sum(д["штраф"] for д in документы)
    if итог_запроса:
        баллы += итог_запроса["баллы"]
        if итог_запроса["штраф"]:
            риск_мин += итог_запроса["штраф"]["наименьший_штраф_руб"]
            риск_макс += итог_запроса["штраф"]["наибольший_штраф_руб"]
        if итог_запроса.get("локализация"):
            риск_мин += итог_запроса["локализация"][0]
            риск_макс += итог_запроса["локализация"][1]
    return max(0, 100 - баллы), баллы, риск_мин, риск_макс


def первоочередные_действия(пересчёт, документы, итог_запроса):
    действия = list(итог_запроса["действия"]) if итог_запроса else []
    по_риску = sorted(пересчёт, key=lambda п: п["расчёт"]["наибольший_штраф_руб"], reverse=True)
    действия += [f"Нарушение № {п['нарушение']['номер']}: {п['нарушение']['что_исправить']}" for п in по_риску]
    действия += [f"Исправить документ {д['файл']}: {д['причина']}" for д in документы if д["состояние"] != "в порядке"]
    уникальные = []
    for д in действия:
        if д not in уникальные:
            уникальные.append(д)
    return уникальные[:5]


