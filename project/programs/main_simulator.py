def загрузить_артефакт(имя_модуля, имя_переменной):
    try:
        модуль = importlib.import_module(имя_модуля)
    except Exception as ошибка:  # файл отсутствует или в нём синтаксическая ошибка
        остановить_с_ошибкой(f"не удалось подключить {имя_модуля.replace('.', '/')}.py ({ошибка}).")
    if not hasattr(модуль, имя_переменной):
        остановить_с_ошибкой(f"в файле {имя_модуля.replace('.', '/')}.py нет переменной {имя_переменной}.")
    return getattr(модуль, имя_переменной)


def проверить_ключи(запись, ключи, где):
    нет = [к for к in ключи if к not in запись]
    if нет:
        остановить_с_ошибкой(f"{где}: не хватает полей {', '.join(нет)}.")


