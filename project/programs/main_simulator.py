ПСЕВДОНИМЫ_СТРАН = {"US": ["сша", "америк", "штаты"], "AE": ["оаэ", "эмират"], "GB": ["англи", "британи"],
                    "KG": ["кыргыз"], "BY": ["белорусс"], "KR": ["коре"], "ZA": ["юар"]}
ОБЩИЕ_СЛОВА = {"республика", "королевство", "государство", "южная", "северная", "новая", "федерация"}
КЛЮЧИ_ВИДОВ = [
    ("биометрические", r"биометр|лиц[ао]|лиц[уе]\b|лицев|отпечат|голос|радужк|сетчатк"),
    ("специальные", r"здоров|медицин|диагноз|генетич|днк|геном|национальн|религи|политическ|судимост|интимн|спецкатегор"),
    ("общедоступные", r"общедоступн|публичн"),
    ("иные", r"паспорт|телефон|e-?mail|почт|фио|адрес|контакт|анкет|клиент|запис"),
]


def извлечь_число_людей(текст):
    очищенный = re.sub(r"\d{1,2}\.\d{1,2}\.\d{4}", " ", текст)           # убираем даты
    шаблон = re.compile(r"(\d{1,3}(?:[ \u00a0]\d{3})+|\d+(?:[.,]\d+)?)\s*(тыс\w*|млн\w*|миллион\w*|к(?![а-яё]))?", re.I)
    найдено = list(шаблон.finditer(очищенный))
    выбор = next((м for м in найдено if re.match(r"\s*(?:тыс\w*\s+)?(?:клиент|человек|запис|пилот|сотрудник|субъект|польз|анкет|персон|аккаунт)",
                                                очищенный[м.end():], re.I) or м.group(2)), None) or (найдено[0] if найдено else None)
    if not выбор:
        return None
    число = float(re.sub(r"[ \u00a0]", "", выбор.group(1)).replace(",", "."))
    мн = (выбор.group(2) or "").lower()
    if мн.startswith("тыс") or мн == "к":
        число *= 1000
    elif мн.startswith(("млн", "миллион")):
        число *= 1_000_000
    return int(число)


def извлечь_страну(текст, страны):
    низ = текст.lower()
    for м in re.finditer(r"\b[A-Z]{2}\b", текст):          # явный код страны
        if м.group(0) in страны:
            return м.group(0)
    for код, данные in страны.items():
        основы = list(ПСЕВДОНИМЫ_СТРАН.get(код, []))
        for слово in re.split(r"[\s-]+", данные["название"].lower()):
            if len(слово) >= 4 and слово not in ОБЩИЕ_СЛОВА:
                основы.append(слово[:-1] if слово[-1] in "аяйьы" else слово)
        for основа in основы:
            if re.search(rf"(?<![а-яё]){re.escape(основа)}[а-яё]{{0,6}}(?![а-яё])", низ):
                return код
    return None


def извлечь_виды_данных(текст):
    низ = текст.lower()
    return [вид for вид, шаблон in КЛЮЧИ_ВИДОВ if re.search(шаблон, низ)]


def определить_действие(текст):
    низ = текст.lower()
    if re.search(r"утечк|украд|слив|взлом|происшеств|инцидент|похищен|скомпромет", низ):
        return "происшествие"
    if re.search(r"передат|передач|отправ|экспорт|загруз|переслат|перенест|разместит", низ):
        return "передача"
    return None


def извлечь_время_обнаружения(текст, сейчас):
    низ = текст.lower()
    м = re.search(r"(\d+)\s*(час|дн|ден)", низ)
    if м and "назад" in низ:
        return сейчас - (datetime.timedelta(hours=int(м.group(1))) if м.group(2) == "час"
                         else datetime.timedelta(days=int(м.group(1))))
    if "позавчера" in низ:
        return сейчас - datetime.timedelta(days=2)
    if "вчера" in низ:
        return сейчас - datetime.timedelta(days=1)
    return сейчас


def разобрать_запрос(текст, страны):
    """Определяет страну, число людей, вид данных, вид действия и сопутствующие признаки."""
    низ = текст.lower()
    дата = re.search(r"(\d{1,2})\.(\d{1,2})\.(\d{4})", текст)
    причина = re.search(r"(?:из-за|по причине|причина[:\s]+)([^.,;!?]+)", низ)
    цель = re.search(r"для ([^.,;!?]+)", низ)
    return {
        "текст": текст,
        "действие": определить_действие(текст),
        "страна": извлечь_страну(текст, страны),
        "число_людей": извлечь_число_людей(текст),
        "виды_данных": извлечь_виды_данных(текст),
        "повторно": bool(re.search(r"повторн|снова|опять|уже\s+была|вторая", низ)),
        "согласие": False if re.search(r"без\s+согласи|нет\s+согласи|не\s+получал", низ)
                    else (True if re.search(r"с\s+согласи|есть\s+согласи|согласи\w+\s+получен", низ) else None),
        "уведомлён": False if re.search(r"не\s+уведомл|без\s+уведомл", низ)
                     else (True if re.search(r"уведомил|уведомлен|уведомлён", низ) else False),
        "дата_уведомления": datetime.date(int(дата.group(3)), int(дата.group(2)), int(дата.group(1))) if дата else None,
        "причина": причина.group(1).strip() if причина else None,
        "цель": цель.group(1).strip() if цель else None,
        "расследование_завершено": bool(re.search(r"расследовани\w+\s+(?:завершен|закончен)", низ)),
    }


