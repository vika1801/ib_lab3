"""
Задание 3.2. Проверка страны. Данные берутся из data/countries.py через подключение.
"""
import sys
import pathlib

КОРЕНЬ_ПРОЕКТА = pathlib.Path(__file__).resolve().parent.parent
if str(КОРЕНЬ_ПРОЕКТА) not in sys.path:
    sys.path.insert(0, str(КОРЕНЬ_ПРОЕКТА))

from data.countries import СТРАНЫ   # подключение справочника (а не хранение внутри функции)

ЗАКОН_УВЕДОМЛЕНИЕ = "ч. 3 ст. 12 152-ФЗ — уведомление Роскомнадзора до начала трансграничной передачи"
ЗАКОН_ПЕРЕЧЕНЬ = "ч. 2 ст. 12 152-ФЗ — перечень стран с адекватной защитой утверждает Роскомнадзор"
ЗАКОН_ОЖИДАНИЕ = "ч. 12 ст. 12 152-ФЗ — Роскомнадзор рассматривает уведомление 10 рабочих дней (исключение — ч. 11 ст. 12)"


def проверить_страну(код_страны):
    """Возвращает словарь: код, название, приговор, условия, ссылки_на_закон, дней_ожидания."""
    код = str(код_страны).strip().upper()
    запись = СТРАНЫ.get(код)

    if запись is None:
        return {
            "код": код, "название": "не найдена в справочнике",
            "приговор": "запрещено",
            "условия": ["Код страны отсутствует в справочнике: передача невозможна до юридической оценки страны."],
            "ссылки_на_закон": [ЗАКОН_ПЕРЕЧЕНЬ, ЗАКОН_УВЕДОМЛЕНИЕ],
            "дней_ожидания": 10,
        }

    условия = ["Направить уведомление в Роскомнадзор до начала передачи."]
    ссылки = [ЗАКОН_ПЕРЕЧЕНЬ, ЗАКОН_УВЕДОМЛЕНИЕ, "Источник: " + запись["источник"]]

    if запись["конвенция_108"]:
        приговор, дней = "разрешено", 0
        условия.append("Передачу можно начинать сразу после направления уведомления, не дожидаясь решения.")
    elif запись["достаточная_защита"]:
        приговор, дней = "разрешено при условиях", 0
        условия.append("До подачи уведомления получить от получателя сведения о правовом регулировании "
                       "персональных данных в стране (она не участник Конвенции 108) и оценить их достоверность.")
        условия.append("Для биометрии, спецкатегорий и данных несовершеннолетних Роскомнадзор вправе "
                       "запросить дополнительные сведения.")
        условия.append("Передачу можно начинать сразу после направления уведомления.")
    else:
        приговор, дней = "разрешено при условиях", 10
        условия.append("Получить от получателя сведения о мерах защиты данных и условиях прекращения обработки.")
        условия.append("Оценить достоверность сведений; страна не обеспечивает адекватную защиту по перечню.")
        условия.append("Не передавать данные до истечения 10 рабочих дней со дня получения уведомления "
                       "Роскомнадзором (риск решения о запрете или ограничении).")
        ссылки.append(ЗАКОН_ОЖИДАНИЕ)

    return {"код": код, "название": запись["название"], "приговор": приговор,
            "условия": условия, "ссылки_на_закон": ссылки, "дней_ожидания": дней}


if __name__ == "__main__":
    результат = проверить_страну(input("Код страны (например, DE, US, CN): "))
    for ключ, значение in результат.items():
        print(f"{ключ}: {значение}")
