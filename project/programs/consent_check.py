# -*- coding: utf-8 -*-
"""
Задание 2.2. Проверка согласия на обработку персональных данных.
Правила (ч. 1 и ч. 4 ст. 9 152-ФЗ в ред. ФЗ № 156-ФЗ от 24.06.2025):
  1) согласие — отдельный документ, без отсылок к договору/оферте;
  2) есть конкретные цели, перечень данных, срок действия, порядок отзыва;
  3) штраф: 300 000 руб. за любой дефект + 100 000 за каждую недостающую часть
     + 200 000 за «вшитое» согласие, но не более 700 000 руб. (ч. 2 ст. 13.11 КоАП РФ).
При запуске обрабатывает все согласия из data/documents/ и сохраняет отчёт.
"""
import re
import pathlib

КОРЕНЬ_ПРОЕКТА = pathlib.Path(__file__).resolve().parent.parent
ПАПКА_ДОКУМЕНТОВ = КОРЕНЬ_ПРОЕКТА / "data" / "documents"
ПУТЬ_ОТЧЁТА = КОРЕНЬ_ПРОЕКТА / "reports" / "consent_report.txt"

БАЗОВЫЙ_ШТРАФ = 300_000
ШТРАФ_ЗА_ЧАСТЬ = 100_000
ШТРАФ_ЗА_ВШИТОЕ = 200_000
ПРЕДЕЛ_ШТРАФА = 700_000

# Фразы, по которым согласие признаётся «вшитым» в договор, оферту или иной основной документ
ШАБЛОНЫ_ВШИТОГО = [
    r"в\s+соответствии\s+с\s+(?:настоящим\s+|заключ[её]нным\s+)?(?:договор|оферт)",
    r"(?:настоящ\w+|данн\w+)\s+(?:договор|оферт)",
    r"услови\w+\s+(?:настоящего\s+)?(?:договор|оферт)",
    r"неотъемлем\w+\s+част\w+",
    r"согласно\s+(?:договор|оферт)",
    r"публичн\w+\s+оферт|пользовательск\w+\s+соглашени",
    r"п\.\s*\d+(?:\.\d+)*\s+договор",
    r"в\s+рамках\s+(?:договор|оферт)",
    r"принима\w+\s+(?:услови|оферт)|акцепт\w*\s+оферт",
]
# Расплывчатые формулировки, из-за которых цели/данные не считаются конкретными
РАСПЛЫВЧАТЫЕ = [r"в\s+любых\s+целях", r"в\s+иных\s+целях", r"для\s+любых\s+целей",
                r"любые\s+(?:персональные\s+)?данные", r"все\s+(?:мои\s+)?(?:персональные\s+)?данные",
                r"иные\s+цели\s+по\s+усмотрению"]
ЧИСЛОВОЙ_СРОК = r"\d+\s*(?:\([а-яё\s-]+\)\s*)?(?:лет|год|года|месяц\w*|дн\w*)|до\s+\d{2}\.\d{2}\.\d{4}"


def _есть_вшитость(текст):
    """Ищет отсылки к договору/оферте; отрицание («не является ...») не считается."""
    найдено = []
    for шаблон in ШАБЛОНЫ_ВШИТОГО:
        for м in re.finditer(шаблон, текст):
            перед = текст[max(0, м.start() - 25):м.start()]
            if not re.search(r"\bне\s+\w*\s*$|\bбез\s+$", перед):
                найдено.append(м.group(0))
    return найдено


def _расплывчато(текст):
    """Расплывчатая формулировка; запрет («в иных целях не допускается») не считается."""
    for шаблон in РАСПЛЫВЧАТЫЕ:
        for м in re.finditer(шаблон, текст):
            после = текст[м.end():м.end() + 40]
            if not re.search(r"\bне\s+(?:допускается|обрабатыва|осуществля)", после):
                return True
    return False


def _есть_цели(текст):
    return bool(re.search(r"цел(?:ь|и|ей|ях)\s+обработки", текст)) and not _расплывчато(текст)


def _есть_перечень(текст):
    return bool(re.search(r"перечен\w+\s+(?:персональных\s+)?данных", текст)) and not _расплывчато(текст)


def _есть_срок(текст):
    for м in re.finditer(r"срок\w*\s+(?:действия\s+)?согласия|согласие\s+действует", текст):
        if re.search(ЧИСЛОВОЙ_СРОК, текст[м.start():м.end() + 200]):
            return True
    return False


def _есть_отзыв(текст):
    for м in re.finditer(r"отзыв\w*", текст):
        if re.search(r"заявлени|направ|электронн|лично|почт", текст[м.start():м.start() + 250]):
            return True
    return False


def проверить_согласие(текст_согласия, вид_документа):
    """
    Возвращает словарь: правильный_ли_документ, не_хватает_частей, размер_штрафа_руб, пояснение.
    вид_документа: «работник» или «клиент».
    """
    if вид_документа not in ("работник", "клиент"):
        raise ValueError("Вид документа должен быть «работник» или «клиент».")
    текст = текст_согласия.lower()

    вшитое = _есть_вшитость(текст)
    части = {"конкретные цели обработки": _есть_цели(текст),
             "конкретный перечень данных": _есть_перечень(текст),
             "срок действия согласия": _есть_срок(текст),
             "порядок отзыва согласия": _есть_отзыв(текст)}
    не_хватает = [название for название, есть in части.items() if not есть]

    штраф = 0
    пояснение = []
    if вшитое:
        пояснение.append("Согласие «вшито» в другой документ (найдено: «" + "», «".join(sorted(set(вшитое))[:3]) +
                         "»): с 01.09.2025 оно должно быть отдельным документом (ч. 1 ст. 9 152-ФЗ).")
    if не_хватает:
        пояснение.append("Не хватает обязательных частей (ч. 4 ст. 9): " + "; ".join(не_хватает) + ".")
    if вшитое or не_хватает:
        штраф = min(ПРЕДЕЛ_ШТРАФА, БАЗОВЫЙ_ШТРАФ + ШТРАФ_ЗА_ЧАСТЬ * len(не_хватает) +
                    (ШТРАФ_ЗА_ВШИТОЕ if вшитое else 0))
        пояснение.append("Возможный штраф по ч. 2 ст. 13.11 КоАП РФ.")
    else:
        пояснение.append("Документ отдельный, все обязательные части на месте.")

    return {"правильный_ли_документ": not вшитое and not не_хватает,
            "не_хватает_частей": не_хватает,
            "размер_штрафа_руб": штраф,
            "пояснение": " ".join(пояснение)}


def обработать_все_согласия():
    """Проверяет все файлы *_consent.txt из data/documents/, печатает и сохраняет отчёт."""
    строки = ["ОТЧЁТ ПО СОГЛАСИЯМ НА ОБРАБОТКУ ПЕРСОНАЛЬНЫХ ДАННЫХ", "=" * 70]
    результаты = {}
    for файл in sorted(ПАПКА_ДОКУМЕНТОВ.glob("*_consent.txt")):
        вид = "работник" if "employee" in файл.name else "клиент"
        результат = проверить_согласие(файл.read_text(encoding="utf-8"), вид)
        результаты[файл.name] = результат
        строки += [f"Файл: {файл.name} (вид: {вид})",
                   f"  Правильный документ: {'да' if результат['правильный_ли_документ'] else 'нет'}",
                   f"  Не хватает частей: {', '.join(результат['не_хватает_частей']) or 'всё на месте'}",
                   f"  Возможный штраф: {результат['размер_штрафа_руб']:,} руб.".replace(",", " "),
                   f"  Пояснение: {результат['пояснение']}", "-" * 70]
    текст = "\n".join(строки) + "\n"
    ПУТЬ_ОТЧЁТА.parent.mkdir(exist_ok=True)
    ПУТЬ_ОТЧЁТА.write_text(текст, encoding="utf-8")
    return результаты, текст


if __name__ == "__main__":
    print(обработать_все_согласия()[1])
    print(f"Отчёт сохранён: {ПУТЬ_ОТЧЁТА}")
