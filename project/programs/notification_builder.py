# -*- coding: utf-8 -*-
"""
Задание 4.1. Создание уведомления Роскомнадзора об утечке (ч. 3.1 ст. 21 152-ФЗ).
  первичное — в течение 24 часов с момента выявления инцидента (п. 1 ч. 3.1);
  дополнительное — в течение 72 часов, с результатами внутреннего расследования (п. 2 ч. 3.1).
Шаблон берётся из data/documents/leak_notification.txt, числа подставляются программой.
"""
import sys
import pathlib
import datetime

КОРЕНЬ_ПРОЕКТА = pathlib.Path(__file__).resolve().parent.parent
if str(КОРЕНЬ_ПРОЕКТА) not in sys.path:
    sys.path.insert(0, str(КОРЕНЬ_ПРОЕКТА))

from data.organization import ОРГАНИЗАЦИЯ

ПУТЬ_ШАБЛОНА = КОРЕНЬ_ПРОЕКТА / "data" / "documents" / "leak_notification.txt"
ФОРМАТЫ_ВРЕМЕНИ = ("%Y-%m-%d %H:%M", "%d.%m.%Y %H:%M", "%Y-%m-%dT%H:%M")


def _в_время(значение):
    if isinstance(значение, datetime.datetime):
        return значение
    for формат in ФОРМАТЫ_ВРЕМЕНИ:
        try:
            return datetime.datetime.strptime(str(значение), формат)
        except ValueError:
            continue
    raise ValueError(f"Не удалось разобрать дату и время: {значение}")


def создать_уведомление(сведения, путь_к_файлу, текущее_время=None):
    """
    сведения: словарь с ключами «дата_время_обнаружения», «число_пострадавших», «виды_данных»,
              «причина_утечки», «принятые_меры», «расследование_завершено».
    Возвращает словарь: вид уведомления, срок, просрочено ли, путь к файлу.
    """
    сейчас = текущее_время or datetime.datetime.now()
    обнаружено = _в_время(сведения["дата_время_обнаружения"])
    часов = max(0.0, (сейчас - обнаружено).total_seconds() / 3600)

    # Вид уведомления определяется по времени: после 24 часов с завершённым расследованием — дополнительное
    if сведения["расследование_завершено"] and часов > 24:
        вид, срок = "дополнительное", 72
        блок = ("Результаты внутреннего расследования: расследование завершено. "
                f"Причина инцидента: {сведения['причина_утечки']}. "
                "Лица, действия которых стали причиной инцидента: устанавливаются по итогам расследования "
                "(при наличии будут указаны в приложении).")
    else:
        вид, срок = "первичное", 24
        блок = ("Внутреннее расследование "
                + ("завершено." if сведения["расследование_завершено"] else "продолжается.")
                + " Результаты будут направлены дополнительным уведомлением в течение 72 часов с момента выявления.")
    просрочено = часов > срок
    статус = (f"СРОК НАРУШЕН: прошло {часов:.1f} ч., просрочка {часов - срок:.1f} ч. "
              "(риск штрафа по ч. 11 ст. 13.11 КоАП РФ: 1–3 млн руб.)."
              if просрочено else f"Срок соблюдён: прошло {часов:.1f} ч. из {срок}.")

    значения = {
        "вид_уведомления": вид,
        "вид_уведомления_заглавными": вид.upper(),
        "дата_составления": сейчас.strftime("%d.%m.%Y %H:%M"),
        "срок_подачи_часов": срок,
        "статус_срока": статус,
        "наименование_оператора": ОРГАНИЗАЦИЯ["название"],
        "отрасль": ОРГАНИЗАЦИЯ["отрасль"],
        "ответственный": ОРГАНИЗАЦИЯ["ответственный_за_обработку_данных"],
        "дата_обнаружения": обнаружено.strftime("%d.%m.%Y %H:%M"),
        "часов_с_обнаружения": f"{часов:.1f}",
        "число_пострадавших": f"{сведения['число_пострадавших']:,}".replace(",", " "),
        "виды_данных": ", ".join(сведения["виды_данных"]),
        "причина_утечки": сведения["причина_утечки"],
        "предполагаемый_вред": "возможное использование данных в мошеннических целях, "
                               "нарушение неприкосновенности частной жизни субъектов",
        "принятые_меры": сведения["принятые_меры"],
        "сведения_по_виду": блок,
    }
    текст = ПУТЬ_ШАБЛОНА.read_text(encoding="utf-8").format_map(значения)
    путь = pathlib.Path(путь_к_файлу)
    путь.parent.mkdir(parents=True, exist_ok=True)
    путь.write_text(текст, encoding="utf-8")
    return {"вид_уведомления": вид, "срок_часов": срок, "прошло_часов": round(часов, 1),
            "просрочено": просрочено, "путь": str(путь)}


if __name__ == "__main__":
    пример = {"дата_время_обнаружения": (datetime.datetime.now() - datetime.timedelta(hours=30)).strftime("%Y-%m-%d %H:%M"),
              "число_пострадавших": 5000, "виды_данных": ["иные"],
              "причина_утечки": "взлом учётной записи администратора", "принятые_меры": "блокировка доступа, смена ключей",
              "расследование_завершено": True}
    print(создать_уведомление(пример, КОРЕНЬ_ПРОЕКТА / "reports" / "rkn_notification.txt"))
